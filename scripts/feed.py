"""Write feed/: the plain markdown ChatGPT reads from the repository, separate from the website.

feed/index.md is a map, not content: it says which file answers which question, so a reader
opens only the one or two files a request needs. Prices are small files per market and item
category; guide pages aren't copied, the map points to them in content/ with the version an
edit through the inbox quotes back. Everything here is generated by scripts/build.py on every
build and committed with whatever changed it; never edit it by hand.

The output depends only on the data (no build time), so an unchanged repository rebuilds to
identical files and nothing is committed.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
from datetime import datetime, timezone
from pathlib import Path

RAW = "https://raw.githubusercontent.com/faresbn/Tazdingo/main/"
SITE = "https://faresbn.github.io/Tazdingo/"
SPLIT_AT = 150  # a category with more items than this is split by subcategory, to keep each file small
ALERT_ROWS = 30  # each alert list keeps its strongest rows; the full lists are on the website
CREDIT = "Item names, categories, vendor prices and recipes: Data from ForeverDB.net."
PROCESSED = {"auctionator": "processed into the prices above"}  # addons with a processor (scripts/inbox.py)
SECTIONS = (("classes/", "Classes and specs"), ("professions/", "Professions"), ("world/", "World topics"), ("more/", "More"))


VERSION_CHARS = 12  # a page's version: the start of its git blob ID, as `git rev-parse --short=12` would abbreviate it


def blob_id(path: Path) -> str:
    """The file's git blob ID, as git itself computes it (`git hash-object`); its first 12
    characters are the page's version, which an edit through the inbox quotes back."""
    return subprocess.run(["git", "hash-object", str(path)], cwd=path.parent, capture_output=True, text=True,
                          check=True).stdout.strip()


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "other"


def when(timestamp: int | None) -> str:
    return datetime.fromtimestamp(timestamp, timezone.utc).strftime("%Y-%m-%d %H:%M UTC") if timestamp else "unknown"


def cell(text) -> str:
    return "" if text is None else str(text).replace("|", "/").replace("\n", " ")


def link(path: str, label: str | None = None) -> str:
    """A path in the repository; every file states the address it's under once (RAW)."""
    return f"`{path}`" + (f" ({label})" if label else "")


def table(header: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def groups(items: list[dict]) -> dict[str, tuple[str, list[dict]]]:
    """Items by category file: {file slug: (title, items)}; big categories split by subcategory."""
    by_class: dict[str, list[dict]] = {}
    for item in items:
        by_class.setdefault((item.get("category") or {}).get("class") or "Other", []).append(item)
    result = {}
    for name, members in sorted(by_class.items()):
        if len(members) <= SPLIT_AT:
            result[slug(name)] = (name, members)
            continue
        by_sub: dict[str, list[dict]] = {}
        for item in members:
            by_sub.setdefault((item.get("category") or {}).get("subclass") or "Other", []).append(item)
        for sub, part in sorted(by_sub.items()):
            result[slug(f"{name}-{sub}")] = (f"{name}: {sub}", part)
    return result


def market_header(market: dict) -> list[str]:
    ah = market.get("ah") or {}
    kind = "a sample of the Beta market, not the whole of it" if market["sample"] else "every item recorded"
    return [f"- **Market:** {market['name']} ({market['environment_label']}), {kind}.",
            f"- **Latest scan:** {when(ah.get('newest'))}. Uploads in the 30-day window: {ah.get('scans_in_window', 0)}.",
            "- **These are asking prices recorded by Auctionator, not sales.** \"Latest\" is the cheapest listing at the scan named; "
            "\"typical\" is the median daily low over the item's last seven days of records; \"usual\" is the median daily low over "
            "the last 14 full days, needing at least three. Steadiness: steady, moving or volatile; volatile prices are unreliable."]


def item_rows(items: list[dict], money) -> list[list]:
    return [[i["name"], i["id"], money(i.get("latest", i.get("price"))), when(i.get("latest_time")) if i.get("latest_time") else i.get("price_scan"),
             money(i.get("typical")), money(i.get("ref")), i.get("volatility") or "too new",
             f"{i['presence_days']} of {i['presence_of']}" if i.get("presence_of") else "", round(i["listed_median"]) if i.get("listed_median") else "",
             f"{i['change']:+d}%" if i.get("change") is not None else ""] for i in items]


ITEM_HEADER = ["Item", "ID", "Latest", "Recorded at", "Typical", "Usual", "Steadiness", "Days listed", "Units usually listed", "Weekly change"]


def alerts(market: dict, money) -> str:
    ah = market.get("ah") or {}
    parts = [f"# {market['name']}: alerts and estimates", "", *market_header(market), "",
             "Everything below is an estimate from listings, recorded at the time shown; none of it says what sold.", ""]

    def section(title: str, note: str, header: list[str], rows: list[list]) -> None:
        parts.extend([f"## {title}", "", note, ""])
        if len(rows) > ALERT_ROWS:
            parts.extend([f"The strongest {ALERT_ROWS} of {len(rows)}.", ""])
        parts.extend([table(header, rows[:ALERT_ROWS]), ""] if rows else ["None at the latest scan.", ""])

    section("Deals: recorded under the usual price", "At least 20% under the usual price. Exceptional ones are at least 30% under and far outside the item's normal spread; they come first. Confidence says how much history stands behind it; low-confidence ones are left out.",
            ["Item", "ID", "Latest", "Usual", "Under usual", "Exceptional", "Confidence", "Recorded at"],
            [[i["name"], i["id"], money(i["latest"]), money(i["ref"]), f"{i['deal']['discount']:.0%}", "yes" if i["deal"]["exceptional"] else "",
              i["deal"]["confidence"], when(i["latest_time"])] for i in ah.get("deals", [])])
    section("Recorded below what a vendor pays", "Rare or better items and recipes only, at least 1 silver a unit: buying these and selling to a vendor returns more than the listing costs, if the listing is still there.",
            ["Item", "ID", "Latest", "Vendor pays", "Recorded at"],
            [[i["name"], i["id"], money(i["latest"]), money(i["vendor_sell"]), when(i["latest_time"])] for i in ah.get("vendor", [])])
    section("Investment watch", "Steady or moving items, listed most days, recorded at or under their cheaper days. The margin is an estimate after the 5% Auction House cut.",
            ["Item", "ID", "Latest", "Usual", "Estimated margin a unit", "Steadiness", "Recorded at"],
            [[i["name"], i["id"], money(i["latest"]), money(i["ref"]), money(i["invest"]["margin"]), i["volatility"], when(i["latest_time"])]
             for i in ah.get("invest", [])])
    section("Short supply", "At least 20% over usual with at most half the units usually listed, on the last full day.",
            ["Item", "ID", "Latest", "Usual", "Units vs usual", "Recorded at"],
            [[i["name"], i["id"], money(i["latest"]), money(i["ref"]), f"{i['short']['stock']:.0%}", when(i["latest_time"])] for i in ah.get("short", [])])
    section("Rising since the last full day", "The latest recorded price against the last full day's lowest.",
            ["Item", "ID", "Latest", "Change", "Recorded at"],
            [[i["name"], i["id"], money(i["latest"]), f"{i['move']['change']:+d}%", when(i["latest_time"])] for i in ah.get("rising", [])])
    section("Falling since the last full day", "The latest recorded price against the last full day's lowest.",
            ["Item", "ID", "Latest", "Change", "Recorded at"],
            [[i["name"], i["id"], money(i["latest"]), f"{i['move']['change']:+d}%", when(i["latest_time"])] for i in ah.get("falling", [])])
    return "\n".join(parts).rstrip() + "\n"


def characters(record: dict) -> str:
    """feed/characters.md: the account's own characters, from data/characters.json (scripts/characters.py)."""
    chars = record["characters"]
    parts = ["# Characters: progression", "",
             "The account's own characters, each as ForeverDB's addon saved it when the character last logged out or "
             "reloaded. A character played since then is further along. Labels, not names. Levels, gear and skills are "
             "facts from the game; anything else (what to do next) is advice to work out from them.", "",
             table(["Character", "Level", "Item level", "Talents", "Professions", "Recorded"],
                   [[c["label"], c["level"], c["item_level"],
                     ", ".join(f"{k} {v}" for k, v in c["talents"]["points"].items() if v) or "none",
                     ", ".join(f"{p['name']} {p['skill']}/{p['max']}" for p in c["professions"]) or "none",
                     (c["recorded_at"] or "unknown").replace("T", " ").replace("Z", " UTC")] for c in chars])]
    for c in chars:
        parts += ["", f"## {c['label']}", "",
                  f"{c['faction']}, level {c['level']}, item level {c['item_level']}; recorded "
                  f"{(c['recorded_at'] or 'unknown').replace('T', ' ').replace('Z', ' UTC')} on {c['recorded_on'] or 'save'}, build {c['build']}."]
        if c["gear"]:
            parts += ["", table(["Slot", "Item", "Item ID", "Item level"], [[g["slot"], g["name"], g["item"], g["item_level"]] for g in c["gear"]])]
        points = ", ".join(f"{k} {v}" for k, v in c["talents"]["points"].items())
        if points:
            parts += ["", f"Talents: {points}" + (f". Loadout code: `{c['talents']['loadout']}`" if c["talents"].get("loadout") else "") + "."]
        if c["professions"] or c["skills"]:
            parts += ["", table(["Skill", "Kind", "Skill level", "Max"],
                                [[p["name"], "Profession", p["skill"], p["max"]] for p in c["professions"]]
                                + [[s["name"], s["category"], s["skill"], s["max"]] for s in c["skills"]])]
        if c["reputations"]:
            parts += ["", table(["Reputation", "Standing", "Progress"],
                                [[r["name"], r["standing"], f"{r['progress']}/{r['needed']}" if "needed" in r else ""] for r in c["reputations"]])]
        extra = [", ".join(f"{k} {v}" for k, v in c["stats"].items()), ", ".join(f"{k} {v}" for k, v in c["pvp"].items()),
                 ", ".join(f"{k} {v}" for k, v in c["collected"].items())]
        parts += ["", "Stats: " + (extra[0] or "none") + ". PvP: " + (extra[1] or "none") + ". Collected: " + extra[2] + "."]
    return "\n".join(parts) + "\n"


def write(feed: Path, root: Path, markets: list[dict], ctx: dict, money) -> list[str]:
    """Write feed/ from the build's markets and context; returns the files written."""
    if feed.name != "feed":
        raise ValueError("The feed is written only to a folder named feed/ (the repository's, or a test's)")
    if feed.exists():
        shutil.rmtree(feed)
    files: dict[str, str] = {}
    market_lines = []
    for market in markets:
        folder = f"feed/prices/{market['slug']}/"
        cats = groups(market["items"])
        for name, (title, members) in cats.items():
            files[f"{folder}{name}.md"] = "\n".join([
                f"# {market['name']}: {title}", "", *market_header(market), "",
                table(ITEM_HEADER, item_rows(members, money)), "", CREDIT]) + "\n"
        files[f"{folder}alerts.md"] = alerts(market, money)
        files[f"{folder}index.md"] = "\n".join([
            f"# {market['name']}: map", "", *market_header(market), "",
            "Open only the file for the item's category. Each lists every item recorded in it with its latest, typical and usual price.", "",
            f"Paths are in the repository: {RAW}<path>", "",
            f"- {link(folder + 'alerts.md')}: deals under the usual price, below vendor price, investment watch, short supply and movers.",
            *[f"- {link(f'{folder}{name}.md')}: {title}, {len(members)} items." for name, (title, members) in cats.items()],
            "", f"For people, the same market on the website: {SITE}prices/{market['slug']}/", "", CREDIT]) + "\n"
        ah = market.get("ah") or {}
        market_lines.append(f"- {link(folder + 'index.md')}: {market['name']} ({market['environment_label']}), "
                            f"{len(market['items'])} items, latest scan {when(ah.get('newest'))}"
                            + (", a Beta sample" if market["sample"] else "") + ".")
    craft_note = ("Estimated listing margins: what the item lists for against what its reagents cost. Our typical price counts when "
                  "it's current, listed at least five times and not volatile; otherwise other players' median on ForeverDB. Estimates, not sales.")
    by_profession: dict[str, list[dict]] = {}
    for row in ctx["craft"]:
        by_profession.setdefault(row["profession"], []).append(row)
    for profession, rows in sorted(by_profession.items()):
        files[f"feed/craft/{slug(profession)}.md"] = "\n".join([
            f"# What to craft: {profession}", "", craft_note, "",
            table(["Recipe", "Skill", "Item ID", "Makes", "Sells for", "Costs", "Margin", "Price from"],
                  [[r["name"], r["skill"], r["item"], r["count"], money(r["sells"]), money(r["cost"]), money(r["margin"]), r["value_source"]]
                   for r in rows]), "", CREDIT]) + "\n"
    files["feed/craft/index.md"] = "\n".join([
        "# What to craft: map", "", craft_note, "", f"Paths are in the repository: {RAW}<path>", "",
        *[f"- {link(f'feed/craft/{slug(p)}.md')}: {p}, {len(rows)} recipes with a margin." for p, rows in sorted(by_profession.items())],
        "", CREDIT]) + "\n"
    page_lines = []
    content = ctx["content"]
    for prefix, title in SECTIONS:
        keys = sorted(k for k in content if k.startswith(prefix))
        if not keys:
            continue
        page_lines += ["", f"### {title}", ""]
        for key in keys:
            page = content[key]
            path = page["file"]
            page_lines.append(f"- {link(path)}: {page['title']}, updated {page['updated']}, {page['status_label']}, "
                              f"version `{blob_id(root / path)[:VERSION_CHARS]}`")
    files["feed/guides.md"] = "\n".join([
        "# Guide pages: map", "",
        f"Every guide page, with its version. Paths are in the repository: {RAW}<path>", "",
        "Pre-launch means the page's advice isn't checked in the live game yet. To edit a page, read it at its path, "
        "then submit the whole file through the inbox with the version shown here.", *page_lines, ""]) + "\n"
    chars_path = root / "data/characters.json"
    chars = json.loads(chars_path.read_text()) if chars_path.is_file() else None
    if chars:
        files["feed/characters.md"] = characters(chars)
    addon_lines = []
    for environment in sorted(p for p in (root / "data/captures").iterdir() if p.is_dir()) if (root / "data/captures").is_dir() else []:
        for addon in sorted(p for p in environment.iterdir() if p.is_dir()):
            kept = sorted(addon.glob("*.lua"))
            if kept:
                addon_lines.append(f"- `{kept[-1].relative_to(root).as_posix()}`: the latest of {len(kept)} {addon.name} file(s) "
                                   f"({environment.name}), {PROCESSED.get(addon.name, 'stored, not processed yet')}.")
    files["feed/index.md"] = "\n".join([
        "# Tazdingo feed: start here", "",
        "This is a map. It holds no prices or guide text; it tells you which file to open. Open only the files the question needs.", "",
        f"Every path below is in the public repository: {RAW}<path>", "",
        "## Where to go", "",
        *market_lines,
        f"- {link('feed/craft/index.md')}: what to craft, by profession, with estimated margins.",
        f"- {link('feed/guides.md')}: every class, spec, profession, world and More page, with its path and version.",
        *([f"- {link('feed/characters.md')}: the account's own characters (level, gear, talents, professions, reputations), "
           f"as last saved in the game."] if chars else []),
        "- Combat logs, on the repository's `logs` branch: https://raw.githubusercontent.com/faresbn/Tazdingo/logs/README.md "
        "is the guide and the list. Instance runs complete (every player, as the game wrote them) and open-world summaries "
        "of our own characters; read the guide first, the instance files are large.",
        *(["", "Original addon files, as uploaded (large; open only when asked about that addon):", *addon_lines] if addon_lines else []), "",
        "## How the data stays current", "",
        "- **Auction House prices:** each time the game saves Auctionator's file (a `/reload` or logout after a scan), the "
        "scan is imported and published within minutes. A save with no new scan adds nothing. Times quoted are when the scan "
        "was made, not when it was imported.",
        "- **ForeverDB data** (recipes, trainers, abilities, vendor and other players' prices, item names): refreshed three "
        "times a day. When the game build changes, the full refresh takes a couple of hours.",
        "- **Blizzard's posts:** collected every two hours.",
        "- **Combat logs:** with the ForeverDB refresh, each finished combat log is filed on the `logs` branch: the last "
        "14 days or 10 logs per character below level 60, whichever is more; none for level-60 characters.",
        "- **Characters:** with the ForeverDB refresh, the account's own characters are read from ForeverDB's addon file "
        "(`feed/characters.md`), under labels, not names. Each is as of that character's last logout or reload.", "",
        "## How to answer", "",
        "- **Prices:** open the market's map, then only the category file the item belongs to, or `alerts.md` for bargains, "
        "investments and movers. Quote the latest, typical or usual price with its scan time and steadiness. They're asking prices, "
        "not sales. Never mix markets.",
        "- **Guides:** open the page from the guide map and say how current it is; Pre-launch means unverified in the live game.",
        "- **Editing a page:** read it, keep everything still true, and submit the whole file through the inbox with its version "
        "from the guide map (instructions: TAZDINGO_INBOX.md in the project). If the page changed since, the inbox holds the edit; read it again.",
        f"- **People** use the website, not these files: {SITE}", "",
        CREDIT]) + "\n"
    for path, text in files.items():
        target = feed.parent / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    return sorted(files)
